'''
No caso abaixo o aluno colocaria a 1º nota e a 2º para tira a média do semestre.
'''

P1 = float(input("Nota 1:"))
P2 = float(input("Nota 2:"))

Soma = ((P1 + P2) / 2)

print(f"A média de {P1} e {P2} e igual a {Soma}")

